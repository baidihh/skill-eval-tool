"""Internal contracts only; these are NOT names of any vendor's existing API."""
from typing import Protocol,Dict,Any

class ExpertAdapter(Protocol):
    def capabilities(self) -> Dict[str,Any]: ...
    def snapshot_expert(self,expert_id:str) -> Dict[str,Any]: ...
    def prepare_case(self,case_context:Dict[str,Any]) -> Dict[str,Any]: ...
    def submit(self,expert_id:str,execution_input:Dict[str,Any],idempotency_key:str) -> Dict[str,Any]: ...
    def lookup_by_key(self,idempotency_key:str) -> Dict[str,Any]: ...
    def poll(self,external_run_id:str) -> Dict[str,Any]: ...
    def collect(self,external_run_id:str) -> Dict[str,Any]: ...
    def cancel(self,external_run_id:str) -> Dict[str,Any]: ...
